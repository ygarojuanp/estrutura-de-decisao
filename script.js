function somaMaior() {
    let A = Number(prompt("Digite um numero:"));
    let B = Number(prompt("Digite um numero:"));
    let C = Number(prompt("Digite um numero:"));
    let soma = A + B;

    if (soma < C) {
        alert("A soma de A+B é: " + soma)

    } else {
        console.log("Fim!")
    }

}

